// Graph-only regression; requires the Flask server and Leaflet CDN access.
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
require('node:fs').mkdirSync('artifacts', {recursive: true});
(async () => {
  const browser = await chromium.launch({channel: 'msedge', headless: true});
  try {
    const page = await browser.newPage({viewport: {width: 1440, height: 1100}});
    const errors = [];
    let graphRequests = 0, routeRequests = 0, contextRequests = 0, nodeRequests = 0;
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => {
      if (request.url().endsWith('/api/graph')) graphRequests++;
      if (request.url().endsWith('/api/route')) routeRequests++;
      if (request.url().endsWith('/api/graph-context')) contextRequests++;
      if (request.url().endsWith('/api/nodes')) nodeRequests++;
    });
    await page.goto(process.env.TEST_BASE_URL || 'http://127.0.0.1:5003');
    await page.waitForFunction(() => document.querySelector('#ops-status-text').textContent.startsWith('Ready'));
    const toggle = page.locator('#nav-btn-graph');
    assert.equal(await toggle.evaluate(el => el.previousElementSibling.id), 'nav-btn-traffic');
    assert.equal(await page.locator('.graph-canvas').count(), 0);
    await toggle.click();
    await page.waitForFunction(() => Number(document.querySelector('.graph-canvas')?.dataset.roads) > 8000);
    await page.waitForFunction(() => !document.querySelector('#nav-btn-graph').disabled);
    assert.equal(await toggle.getAttribute('aria-pressed'), 'true');
    await page.waitForFunction(() => Number(document.querySelector('.graph-canvas')?.dataset.contextRoads) > 10000);
    assert.equal(await page.locator('#graph-caption strong').count(), 0);
    assert.equal(await page.locator('#map').evaluate(el => el.clientHeight), 520);
    await page.locator('#map').click({position: {x: 20, y: 300}});
    assert.equal(await page.locator('.clean-circle-marker').count(), 0, 'surrounding roads must not enlarge the working sector');
    await page.screenshot({path: 'artifacts/graph-context-preview.png'});
    assert.equal(await page.locator('#map .leaflet-tile-pane img').count(), 0);
    assert.equal(routeRequests, 0);
    await page.locator('#tab-right-settings').click();
    const nodeToggle = page.locator('#show-nodes-toggle');
    assert.equal(await nodeToggle.isChecked(), false);
    const nodesResponse = page.waitForResponse(r => r.url().endsWith('/api/nodes'));
    await nodeToggle.check();
    const nodeData = await (await nodesResponse).json();
    assert.ok(nodeData.count > 5000);
    await page.waitForFunction(() => document.querySelector('.working-nodes-canvas')?.dataset.nodes);
    assert.equal(Number(await page.locator('.working-nodes-canvas').getAttribute('data-nodes')), nodeData.count);
    await page.screenshot({path: 'artifacts/graph-nodes-preview.png'});
    await nodeToggle.uncheck();
    assert.equal(await page.locator('.working-nodes-canvas').count(), 0);
    await nodeToggle.check();
    await page.waitForFunction(() => document.querySelector('.working-nodes-canvas'));
    assert.equal(nodeRequests, 1, 'node data should be cached across on/off toggles');
    await nodeToggle.uncheck();
    await page.locator('#tab-right-route').click();
    await page.locator('#start-landmark-select').selectOption('station');
    await page.locator('#dest-landmark-select').selectOption('clock_tower');
    await page.locator('#algorithm-select').selectOption('dijkstra');
    await page.locator('#calculate-route-btn').click();
    await page.waitForFunction(() => Number(document.querySelector('.graph-canvas')?.dataset.expanded) > 50);
    await page.locator('#resume-playback-btn').click();
    const snapshot = await page.locator('.graph-canvas').getAttribute('data-expanded');
    const summary = await page.locator('.summary-list').textContent();
    await page.waitForTimeout(250);
    assert.equal(await page.locator('.graph-canvas').getAttribute('data-expanded'), snapshot);
    assert.equal(await page.locator('.summary-list').textContent(), summary);
    assert.equal(await page.locator('.route-core').count(), 0, 'graph must not use real-map route effects');
    await page.screenshot({path: 'artifacts/graph-search-preview.png'});
    const buildsBefore = Number(await page.locator('.graph-canvas').getAttribute('data-rebuilds'));
    await page.locator('#btn-zoom-in').click();
    await page.waitForTimeout(500);
    const buildsAfter = Number(await page.locator('.graph-canvas').getAttribute('data-rebuilds'));
    assert.ok(buildsAfter - buildsBefore <= 2, 'zoom must reuse its bitmap, not reproject every frame');
    await page.locator('#btn-recenter').click();
    await page.waitForTimeout(500);
    console.log('Cached graph rebuild:', await page.locator('.graph-canvas').getAttribute('data-rebuild-ms'), 'ms');
    await page.locator('#resume-playback-btn').click();
    await page.locator('#anim-speed-select').selectOption('2');
    await page.waitForFunction(() => document.querySelector('.graph-canvas')?.dataset.phase === 'route');
    await page.waitForTimeout(200);
    const partial = Number(await page.locator('.graph-canvas').getAttribute('data-route-progress'));
    assert.ok(partial > 0 && partial < 1);
    await page.locator('#resume-playback-btn').click();
    const frozen = await page.locator('.graph-canvas').getAttribute('data-route-progress');
    await page.waitForTimeout(150);
    assert.equal(await page.locator('.graph-canvas').getAttribute('data-route-progress'), frozen);
    await page.locator('#resume-playback-btn').click();
    await page.waitForFunction(() => document.querySelector('.graph-canvas')?.dataset.phase === 'complete');
    await page.screenshot({path: 'artifacts/graph-route-preview.png'});
    assert.equal(await page.locator('.graph-canvas').getAttribute('data-route-progress'), '1');
    await toggle.click();
    await page.waitForFunction(() => !document.querySelector('#nav-btn-graph').disabled);
    assert.equal(await page.locator('.graph-canvas').count(), 0);
    assert.equal(await toggle.getAttribute('aria-pressed'), 'false');
    assert.equal(await page.locator('#map').evaluate(el => el.clientHeight), 520);
    assert.equal(await page.locator('.clean-circle-marker').count(), 2);
    await page.waitForFunction(() => document.querySelector('.route-core'));
    await page.waitForFunction(() => document.querySelector('#ops-status-text').textContent.startsWith('Route Active'));
    assert.equal(await page.locator('.route-flow').count(), 1);
    await page.locator('#tab-right-settings').click();
    await nodeToggle.check();
    await page.waitForFunction(() => document.querySelector('.working-nodes-canvas'));
    assert.equal(Number(await page.locator('.working-nodes-canvas').getAttribute('data-nodes')), nodeData.count);
    await page.locator('#tab-right-route').click();
    await toggle.click();
    await page.waitForFunction(() => !document.querySelector('#nav-btn-graph').disabled);
    await page.waitForFunction(() => Number(document.querySelector('.graph-canvas')?.dataset.expanded) > 0);
    assert.equal(graphRequests, 1, 'graph data should load once');
    assert.equal(contextRequests, 1, 'surrounding roads should load once');
    assert.equal(routeRequests, 1, 'switching renderers must reuse the calculated route');
    await page.locator('#clear-route-btn').click();
    assert.equal(await page.locator('.graph-canvas').getAttribute('data-phase'), 'idle');
    assert.equal(await page.locator('.working-nodes-canvas').count(), 1, 'static nodes follow the setting independently of route clearing');
    assert.equal(await page.locator('.clean-circle-marker').count(), 0);
    assert.equal(await page.locator('#summary-distance').textContent(), '—');
    await page.locator('#map').click({position: {x: 470, y: 250}});
    await page.locator('#map').click({position: {x: 550, y: 290}});
    assert.equal(await page.locator('.clean-circle-marker').count(), 2, 'graph supports manual endpoints');
    await page.locator('#algorithm-select').selectOption('a*');
    await page.locator('#calculate-route-btn').click();
    await page.waitForFunction(() => document.querySelector('.graph-canvas')?.dataset.phase === 'complete');
    assert.deepEqual(errors, []);
    console.log('PASS: graph toggle/data caching, live search and route reveal, pause/resume, zoom, view switching, unchanged real-map effects, clear and manual graph selection');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
